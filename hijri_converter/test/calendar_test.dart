  [2169, 6, 27, HijriMethod.civil, 1595, 6, 2],
  [2169, 6, 27, HijriMethod.astronomical, 1595, 6, 3],
  [2169, 10, 4, HijriMethod.ummAlQura, 1595, 9, 13],
  [2169, 10, 4, HijriMethod.civil, 1595, 9, 13],
  [2169, 10, 4, HijriMethod.astronomical, 1595, 9, 14],
];

void main() {
  test('Gregorian → Hijri matches ICU for all methods', () {
    for (final r in refs) {
      final g = DateTime.utc(r[0] as int, r[1] as int, r[2] as int);
      final m = r[3] as HijriMethod;
      expect(
        toHijri(g, m),
        HijriDate(r[4] as int, r[5] as int, r[6] as int),
        reason: '$g ${m.name}',
      );
    }
  });

  test('Hijri → Gregorian round-trips', () {
    for (final r in refs) {
      final g = DateTime.utc(r[0] as int, r[1] as int, r[2] as int);
      final m = r[3] as HijriMethod;
      final h = HijriDate(r[4] as int, r[5] as int, r[6] as int);
      expect(toGregorian(h, m), g, reason: '$h ${m.name}');
    }
  });

  test('Known dates', () {
    // 1 Ramadan 1447 = Wednesday 18 Feb 2026 (Umm al-Qura)
    final g = toGregorian(const HijriDate(1447, 9, 1), HijriMethod.ummAlQura)!;
    expect(g, DateTime.utc(2026, 2, 18));
    expect(weekdaysAr[g.weekday], 'الأربعاء');
    expect(
      toGregorian(const HijriDate(1447, 9, 1), HijriMethod.astronomical),
      DateTime.utc(2026, 2, 17),
    );
  });

  test('Day 30 in a 29-day month is rejected', () {
    for (var m = 1; m <= 12; m++) {
      final len = monthLength(HijriMethod.ummAlQura, 1447, m);
      expect(
        toGregorian(HijriDate(1447, m, 30), HijriMethod.ummAlQura) != null,
        len == 30,
      );
    }
  });
}
